"""Resolve, verify and bundle the latest official stable Pikafish + matching net.

Production Gradle preBuild invokes this before compilation. A failed online
check or unsupported release layout aborts the build, never publishes old bytes.
"""
import argparse, hashlib, json, os, pathlib, re, shutil, struct, subprocess, tempfile, urllib.request

ROOT=pathlib.Path(__file__).resolve().parents[1]
ASSETS=ROOT/'app/src/main/assets'
META=ASSETS/'pikafish-release.json'
JAVA=ROOT/'app/src/main/java/org/xiangqi/study/PikafishRelease.java'
ANDROID=ROOT/'app/src/main/jniLibs/arm64-v8a/libpikafish.so'
NET=ASSETS/'pikafish.nnue'
CACHE=ROOT/'.cache/pikafish'
API='https://api.github.com/repos/official-pikafish/Pikafish/releases/latest'

def digest(path):
    with path.open('rb') as stream:return hashlib.file_digest(stream,'sha256').hexdigest()
def request(url):
    return urllib.request.urlopen(urllib.request.Request(url,headers={'User-Agent':'XiangqiStudy-build','Accept':'application/vnd.github+json','Cache-Control':'no-cache'}),timeout=60)
def write(path,data):
    path.parent.mkdir(parents=True,exist_ok=True)
    if path.exists() and path.read_bytes()==data:return
    temporary=path.with_name(path.name+'.tmp');temporary.write_bytes(data);os.replace(temporary,path)
def min_api(path):
    data=path.read_bytes()
    if data[:6]!=b'\x7fELF\x02\x01' or struct.unpack_from('<H',data,18)[0]!=183:
        raise RuntimeError('Expected official little-endian ELF64 AArch64 executable')
    offset=struct.unpack_from('<Q',data,40)[0]
    size,count,names=struct.unpack_from('<HHH',data,58)
    string_header=offset+names*size
    start,length=struct.unpack_from('<QQ',data,string_header+24)
    strings=data[start:start+length]
    for i in range(count):
        header=offset+i*size;name_index=struct.unpack_from('<I',data,header)[0]
        name=strings[name_index:].split(b'\0',1)[0]
        if name!=b'.note.android.ident':continue
        start,length=struct.unpack_from('<QQ',data,header+24);cursor=start
        while cursor+12<=start+length:
            name_size,desc_size,kind=struct.unpack_from('<III',data,cursor);cursor+=12
            note_name=data[cursor:cursor+name_size].rstrip(b'\0');cursor+=(name_size+3)&~3
            description=data[cursor:cursor+desc_size];cursor+=(desc_size+3)&~3
            if note_name==b'Android' and len(description)>=4:return struct.unpack_from('<I',description)[0]
    raise RuntimeError('Official Android API note missing; release requires review')
def java_source(meta):
    fields={'VERSION':meta['version'],'TAG':meta['tag'],'RELEASE_URL':meta['releaseUrl'],
        'SOURCE_URL':meta['sourceUrl'],'LICENSE_URL':meta['licenseUrl'],
        'ARCHIVE_SHA256':meta['archive']['sha256'],'ANDROID_SHA256':meta['android']['sha256'],
        'NNUE_SHA256':meta['network']['sha256']}
    lines=['package org.xiangqi.study;','','/** Generated by scripts/sync-pikafish.py from verified official release bytes. */','public final class PikafishRelease {','    private PikafishRelease() {}']
    lines += ['    public static final String '+key+' = '+json.dumps(value)+';' for key,value in fields.items()]
    lines += ['    public static final long NNUE_BYTES = '+str(meta['network']['bytes'])+'L;',
        '    public static final int MIN_ANDROID_API = '+str(meta['android']['minApi'])+';','}','']
    return '\n'.join(lines).encode()

def notice_source(meta):
    return (f"# Verified official Pikafish {meta['version']}\n\n"
        f"Release: {meta['releaseUrl']}\n\nExact source: {meta['sourceUrl']}\n\n"
        f"Archive SHA-256: `{meta['archive']['sha256']}`\n\nAndroid AArch64 SHA-256: `{meta['android']['sha256']}`\n\n"
        f"Matching NNUE SHA-256: `{meta['network']['sha256']}` ({meta['network']['bytes']} bytes).\n\n"
        f"The unmodified static Android executable declares API {meta['android']['minApi']}. It is packaged as libpikafish.so and launched as a UCI process, not loaded with JNI.\n\n"
        'Engine: GPL-3.0; see Copying.txt and AUTHORS. The matching NNUE has separate noncommercial terms; see NNUE-License.md. The parent MIT license does not relicense these files.\n\n'
        'Every production preBuild checks the official stable release online and verifies/updates the executable, matching network and notices before compilation. Failure stops the build. Analysis defaults use all available cores, adaptive hash and untimed depth-128 search; controls are in Settings.\n').encode()

def verified_archive(asset,expected):
    name=asset['name']
    if not isinstance(name,str) or not name or '/' in name or '\\' in name or ':' in name or name in ('.','..'):
        raise RuntimeError('Official archive has an unsupported filename')
    archive=CACHE/name
    shared=pathlib.Path(r'C:\Dev\Tools\agent-tooling\downloads')/name
    if shared.is_file() and digest(shared)==expected:return shared
    if not archive.is_file() or digest(archive)!=expected:
        temporary=archive.with_suffix(archive.suffix+'.download')
        try:
            with request(asset['browser_download_url']) as source,temporary.open('wb') as target:shutil.copyfileobj(source,target)
            if digest(temporary)!=expected:raise RuntimeError('Official release archive digest mismatch')
            os.replace(temporary,archive)
        finally:
            if temporary.exists():temporary.unlink()
    return archive

def sync(check_only=False):
    CACHE.mkdir(parents=True,exist_ok=True)
    with request(API) as response:release=json.load(response)
    tag=release['tag_name'];match=re.fullmatch(r'Pikafish-(\d{4}-\d{2}-\d{2})',tag)
    if not match or release.get('prerelease') or release.get('draft'):raise RuntimeError('Unsupported official stable tag')
    version=match.group(1)
    candidates=[a for a in release['assets'] if a['name'].lower().endswith('.7z')]
    if len(candidates)!=1:raise RuntimeError('Expected one official unified .7z package')
    asset=candidates[0];expected=asset.get('digest','')
    if not re.fullmatch(r'sha256:[0-9a-f]{64}',expected):raise RuntimeError('Official asset SHA-256 unavailable')
    expected=expected.split(':',1)[1]
    archive=verified_archive(asset,expected)
    seven=shutil.which('7z') or r'C:\Program Files\7-Zip\7z.exe'
    if not pathlib.Path(seven).is_file():raise RuntimeError('7-Zip is required to verify the official package')
    # Local metadata is a generated receipt, never an authority for engine/net
    # hashes. Derive it afresh from the SHA-verified official archive each run.
    with tempfile.TemporaryDirectory(prefix='unpack-',dir=CACHE) as temp:
        folder=pathlib.Path(temp)
        files=['Pikafish-Android-arm64-universal','pikafish.nnue','Copying.txt','NNUE-License.md','AUTHORS']
        subprocess.run([seven,'e',str(archive),'-o'+str(folder),'-y',*files],check=True,stdout=subprocess.DEVNULL,timeout=180)
        if not all((folder/name).is_file() for name in files):raise RuntimeError('Official release layout changed; build stopped')
        binary=folder/files[0];network=folder/files[1]
        meta={'schema':1,'tag':tag,'version':version,'releaseUrl':release['html_url'],
            'sourceUrl':'https://github.com/official-pikafish/Pikafish/tree/'+tag,
            'licenseUrl':'https://github.com/official-pikafish/Pikafish/blob/'+tag+'/Copying.txt',
            'archive':{'url':asset['browser_download_url'],'sha256':expected},
            'android':{'sha256':digest(binary),'minApi':min_api(binary)},
            'network':{'sha256':digest(network),'bytes':network.stat().st_size}}
        artifacts={ANDROID:binary.read_bytes(),NET:network.read_bytes(),
            META:(json.dumps(meta,indent=2)+'\n').encode(),JAVA:java_source(meta)}
        for destination in (ROOT/'third_party/pikafish',ASSETS/'licenses'):
            for name in files[2:]:artifacts[destination/name]=(folder/name).read_bytes()
            artifacts[destination/'UPSTREAM.md']=notice_source(meta)
        if check_only:
            changed=[str(path.relative_to(ROOT)) for path,data in artifacts.items() if not path.is_file() or path.read_bytes()!=data]
            if changed:raise RuntimeError('Bundled Pikafish is stale or changed; run sync-pikafish.py: '+', '.join(changed))
        else:
            for path,data in artifacts.items():write(path,data)
    print('PASS latest official Pikafish',version,'matching NNUE',meta['network']['sha256'])
    return meta

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check-only',action='store_true')
    args=parser.parse_args()
    try:sync(args.check_only)
    except Exception as error:raise SystemExit('Pikafish build guard failed: '+str(error))
